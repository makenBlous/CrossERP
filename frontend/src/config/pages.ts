export interface PageDef {
  id: string
  path: string
  group: PageGroupId | null
  name: Record<AppLocale, string>
  purpose: Record<AppLocale, string>
  blocks: Record<AppLocale, string[]>
  roles: Role[]
  icon: string
  phase: PagePhase
  implemented: boolean
  showInMenu: boolean
  public: boolean
  unauthenticatedOnly: boolean
  layout: 'blank' | 'default'
}

interface PageInput {
  id: string
  path: string
  group: PageGroupId | null
  nameZh: string
  nameEn: string
  purposeZh: string
  purposeEn: string
  blocksZh: string[]
  blocksEn: string[]
  roles: Role[]
  icon: string
  phase: PagePhase
  implemented?: boolean
  showInMenu?: boolean
  public?: boolean
  unauthenticatedOnly?: boolean
  layout?: 'blank' | 'default'
}

