function page(input: PageInput): PageDef {
  return {
    id: input.id,
    path: input.path,
    group: input.group,
    name: { 'zh-CN': input.nameZh, 'en': input.nameEn },
    purpose: { 'zh-CN': input.purposeZh, 'en': input.purposeEn },
    blocks: { 'zh-CN': input.blocksZh, 'en': input.blocksEn },
    roles: input.roles,
    icon: input.icon,
    phase: input.phase,
    implemented: input.implemented ?? false,
    showInMenu: input.showInMenu ?? false,
    public: input.public ?? false,
    unauthenticatedOnly: input.unauthenticatedOnly ?? false,
    authenticated: input.authenticated,
    layout: input.layout ?? 'default',
    requiredPermissions: input.requiredPermissions ?? (input.public ? undefined : ['system:read']),
    requiredAnyPermissions: input.requiredAnyPermissions,
    module: input.module,
    batch: input.batch,
    erpnextRef: input.erpnextRef,
    odooRef: input.odooRef,
  }
}

