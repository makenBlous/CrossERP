const paramPages = pageCatalog.filter(item => item.path.includes(':'))

function pathToRegExp(path: string) {
  return new RegExp(`^${path.replace(/:[^/]+/g, '[^/]+')}$`)
}

export function findPageById(id: string) {
  return pageCatalog.find(item => item.id === id)
}

export function findPageByPath(path: string) {
  const normalized = path.length > 1 && path.endsWith('/') ? path.slice(0, -1) : path
  const exact = pageCatalog.find(item => item.path === normalized)

  if (exact)
    return exact

  return paramPages.find(item => pathToRegExp(item.path).test(normalized))
}

export function canRoleOpen(role: Role, item: PageDef) {
  if (item.public)
    return true

  if (item.authenticated)
    return true

  if (item.path === '/not-authorized' || item.path === '/me/data-scope')
    return true

  // 采购上手清单和新建采购单不授予 document:read，只放行这两页。
  if (role === 'purchaser' && (item.path === '/onboarding' || item.path === '/procurement/orders/new'))
    return true

  if ((item.path === '/admin/roles' || item.path === '/admin/permission-matrix') && !['admin', 'operator', 'finance', 'viewer', 'auditor'].includes(role))
    return role === 'owner_manager' || role === 'auditor_template'

  const requiredPermissions = item.requiredPermissions
  if (requiredPermissions?.length && !requiredPermissions.every(permissionKey => canPermission(roleSubject(role), permissionKey)))
    return false

  const requiredAnyPermissions = item.requiredAnyPermissions
  if (requiredAnyPermissions?.length && !requiredAnyPermissions.some(permissionKey => canPermission(roleSubject(role), permissionKey)))
    return false

  if (!requiredPermissions?.length && !requiredAnyPermissions?.length)
    return false

  const legacyRoles: Role[] = ['admin', 'operator', 'finance', 'viewer', 'auditor']
  if (legacyRoles.includes(role)) {
    if (!item.roles.includes(role))
      return false

    return item.requiredPermissions?.every(permissionKey => canPermission(roleSubject(role), permissionKey)) ?? true
  }

  return item.requiredPermissions?.every(permissionKey => canPermission(roleSubject(role), permissionKey)) ?? true
}
